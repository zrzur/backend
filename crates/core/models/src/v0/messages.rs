impl From<SystemMessage> for String {
    fn from(s: SystemMessage) -> String {
        match s {
            SystemMessage::Text { content } => content,
            SystemMessage::UserAdded { .. } => "User added to the channel.".to_string(),
            SystemMessage::UserRemove { .. } => "User removed from the channel.".to_string(),
            SystemMessage::UserJoined { .. } => "User joined the channel.".to_string(),
            SystemMessage::UserLeft { .. } => "User left the channel.".to_string(),
            SystemMessage::UserKicked { .. } => "User kicked from the channel.".to_string(),
            SystemMessage::UserBanned { .. } => "User banned from the channel.".to_string(),
            SystemMessage::ChannelRenamed { .. } => "Channel renamed.".to_string(),
            SystemMessage::ChannelDescriptionChanged { .. } => {
                "Channel description changed.".to_string()
            }
            SystemMessage::ChannelIconChanged { .. } => "Channel icon changed.".to_string(),
            SystemMessage::ChannelOwnershipChanged { .. } => {
                "Channel ownership changed.".to_string()
            }
            SystemMessage::MessagePinned { .. } => "Message pinned.".to_string(),
            SystemMessage::MessageUnpinned { .. } => "Message unpinned.".to_string(),
            SystemMessage::CallStarted { .. } => "Call started.".to_string(),
            SystemMessage::AutoModAlert { .. } => "AutoMod flagged a message.".to_string(),
            SystemMessage::PollEnded { question, .. } => format!("Poll ended: {question}"),
            SystemMessage::RaidAlert { .. } => {
                "Many people joined in a short time.".to_string()
            }
        }
    }
}

impl PushNotification {
    /// Create a new notification from a given message, author and channel ID
    pub async fn from(msg: Message, author: Option<MessageAuthor<'_>>, channel: Channel) -> Self {
        let config = config().await;

        let icon = if let Some(author) = &author {
            if let Some(avatar) = author.avatar() {
                format!("{}/avatars/{}", config.hosts.autumn, avatar)
            } else {
                format!("{}/users/{}/default_avatar", config.hosts.api, author.id())
            }
        } else {
            format!("{}/assets/logo.png", config.hosts.app)
        };

        let image = msg.attachments.as_ref().and_then(|attachments| {
            attachments
                .first()
                .map(|v| format!("{}/attachments/{}", config.hosts.autumn, v.id))
        });

        let body = if let Some(ref sys) = msg.system {
            sys.clone().into()
        } else if let Some(ref text) = msg.content {
            text.clone()
        } else if let Some(text) = msg.embeds.as_ref().and_then(|embeds| match embeds.first() {
            Some(Embed::Image(_)) => Some("Sent an image".to_string()),
            Some(Embed::Video(_)) => Some("Sent a video".to_string()),
            Some(Embed::Text(e)) => e
                .description
                .clone()
                .or(e.title.clone().or(Some("Empty Embed".to_string()))),
            Some(Embed::Website(e)) => e.title.clone().or(e
                .description
                .clone()
                .or(e.site_name.clone().or(Some("Empty Embed".to_string())))),
            Some(Embed::None) => Some("Empty Message".to_string()), // ???
            None => Some("Empty Message".to_string()),              // ??
        }) {
            text
        } else {
            "Empty Message".to_string()
        };

        let timestamp = SystemTime::now()
            .duration_since(SystemTime::UNIX_EPOCH)
            .expect("Time went backwards")
            .as_secs();

        Self {
            author: author
                .map(|x| x.username().to_string())
                .unwrap_or_else(|| "Zrzur".to_string()),
            icon,
            image,
            body,
            raw_body: None,
            tag: channel.id().to_string(),
            timestamp,
            url: format!("{}/channel/{}/{}", config.hosts.app, channel.id(), msg.id),
            message: msg,
            channel,
        }
    }
}

#[cfg(test)]
mod embed_tests {
    use super::{EmbedAuthor, EmbedFooter, SendableEmbed};
    use crate::v0::EmbedField;
    use validator::Validate;

    #[test]
    fn longer_titles_and_descriptions_fit() {
        let mut e = SendableEmbed {
            title: Some("ع".repeat(256)),
            description: Some("ع".repeat(4096)),
            ..Default::default()
        };
        assert!(e.validate().is_ok(), "256 / 4096 characters, Arabic included");
        e.title = Some("x".repeat(257));
        assert!(e.validate().is_err(), "title over 256");
        e.title = None;
        e.description = Some("x".repeat(4097));
        assert!(e.validate().is_err(), "description over 4096");
    }

    #[test]
    fn text_length_counts_every_visible_part_in_characters() {
        let e = SendableEmbed {
            title: Some("عنوان".to_string()),
            description: Some("وصف".to_string()),
            author: Some(EmbedAuthor { name: "مؤلف".to_string(), url: None, icon_url: None }),
            fields: Some(vec![EmbedField { name: "اسم".to_string(), value: "قيمة".to_string(), inline: false }]),
            footer: Some(EmbedFooter { text: "تذييل".to_string(), icon_url: None }),
            ..Default::default()
        };
        // 5 + 3 + 4 + 3 + 4 + 5 characters (not bytes)
        assert_eq!(e.text_length(), 24);
    }

    fn embed() -> SendableEmbed {
        SendableEmbed {
            title: Some("Match ready".to_string()),
            ..Default::default()
        }
    }

    #[test]
    fn web_links_are_accepted() {
        let mut e = embed();
        e.url = Some("https://zrzur.com/x".to_string());
        e.icon_url = Some("HTTP://example.com/a.png".to_string());
        e.author = Some(EmbedAuthor {
            name: "Bot".to_string(),
            url: Some("https://example.com".to_string()),
            icon_url: Some("https://example.com/i.png".to_string()),
        });
        e.footer = Some(EmbedFooter {
            text: "footer".to_string(),
            icon_url: Some("https://example.com/f.png".to_string()),
        });
        assert_eq!(e.validate_rich(), Ok(()));
    }

    #[test]
    fn other_schemes_are_refused_everywhere() {
        for bad in [
            "javascript:alert(1)",
            " JavaScript:alert(1)",
            "data:text/html,<script>alert(1)</script>",
            "file:///etc/passwd",
            "vbscript:x",
            "//evil.example/x",
            "https://exa mple.com",
            "https://example.com/\nx",
            "http:/example.com",
        ] {
            let mut a = embed();
            a.url = Some(bad.to_string());
            assert!(a.validate_rich().is_err(), "url {bad:?}");
            let mut b = embed();
            b.icon_url = Some(bad.to_string());
            assert!(b.validate_rich().is_err(), "icon_url {bad:?}");
            let mut c = embed();
            c.author = Some(EmbedAuthor {
                name: "x".to_string(),
                url: Some(bad.to_string()),
                icon_url: None,
            });
            assert!(c.validate_rich().is_err(), "author.url {bad:?}");
            let mut d = embed();
            d.footer = Some(EmbedFooter {
                text: "x".to_string(),
                icon_url: Some(bad.to_string()),
            });
            assert!(d.validate_rich().is_err(), "footer.icon_url {bad:?}");
        }
    }
}

