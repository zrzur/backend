impl SendableEmbed {
    /// Check the author, fields and footer, which the derived validator does not reach
    pub fn validate_rich(&self) -> Result<(), String> {
        fn check(what: &str, value: &str, max: usize) -> Result<(), String> {
            let len = value.chars().count();
            if len == 0 || len > max {
                Err(format!("{what} must be 1 to {max} characters"))
            } else {
                Ok(())
            }
        }

        // links and icons are web addresses only: no javascript:, data:,
        // file: or scheme-relative links reach any client
        fn web(what: &str, value: &str) -> Result<(), String> {
            let lower = value.to_ascii_lowercase();
            let rest = lower
                .strip_prefix("https://")
                .or_else(|| lower.strip_prefix("http://"));
            match rest {
                Some(rest)
                    if !rest.is_empty()
                        && !rest.starts_with('/')
                        && !value.chars().any(|c| c.is_whitespace() || c.is_control()) =>
                {
                    Ok(())
                }
                _ => Err(format!("{what} must be an http or https address")),
            }
        }

        for (what, url) in [("url", &self.url), ("icon_url", &self.icon_url)] {
            if let Some(url) = url {
                web(what, url)?;
            }
        }

        for (what, url) in [("image_url", &self.image_url), ("thumbnail_url", &self.thumbnail_url)] {
            if let Some(url) = url {
                check(what, url, 2048)?;
                web(what, url)?;
            }
        }

        if let Some(author) = &self.author {
            check("author.name", &author.name, 256)?;
            for url in [&author.icon_url, &author.url].into_iter().flatten() {
                check("author url", url, 256)?;
                web("author url", url)?;
            }
        }

        if let Some(fields) = &self.fields {
            if fields.len() > 25 {
                return Err("an embed has at most 25 fields".to_string());
            }
            for field in fields {
                check("field.name", &field.name, 256)?;
                check("field.value", &field.value, 1024)?;
            }
        }

        if let Some(footer) = &self.footer {
            check("footer.text", &footer.text, 2048)?;
            if let Some(url) = &footer.icon_url {
                check("footer.icon_url", url, 256)?;
                web("footer.icon_url", url)?;
            }
        }

        Ok(())
    }

    /// Characters all embeds of one message may hold together (title,
    /// description, author, fields and footer), apart from the message text
    pub const TOTAL_TEXT: usize = 6000;

    /// Everything readers see of this embed, for AutoMod
    pub fn visible_text(&self) -> String {
        let mut text: Vec<&str> = [&self.title, &self.description, &self.url]
            .into_iter()
            .flatten()
            .map(String::as_str)
            .collect();
        if let Some(author) = &self.author {
            text.push(&author.name);
        }
        for field in self.fields.iter().flatten() {
            text.push(&field.name);
            text.push(&field.value);
        }
        if let Some(footer) = &self.footer {
            text.push(&footer.text);
        }
        text.join("\n")
    }

    /// Visible characters of this embed (characters, not bytes: an Arabic
    /// letter counts once)
    pub fn text_length(&self) -> usize {
        let count = |text: &str| text.chars().count();
        self.title.as_deref().map_or(0, count)
            + self.description.as_deref().map_or(0, count)
            + self.author.as_ref().map_or(0, |author| count(&author.name))
            + self.fields.as_ref().map_or(0, |fields| {
                fields.iter().map(|f| count(&f.name) + count(&f.value)).sum()
            })
            + self.footer.as_ref().map_or(0, |footer| count(&footer.text))
    }
}

impl MessageAuthor<'_> {
    pub fn id(&self) -> &str {
        match self {
            MessageAuthor::User(user) => &user.id,
            MessageAuthor::Webhook(webhook) => &webhook.id,
            MessageAuthor::System { .. } => "00000000000000000000000000",
        }
    }

    pub fn avatar(&self) -> Option<&str> {
        match self {
            MessageAuthor::User(user) => user.avatar.as_ref().map(|file| file.id.as_str()),
            MessageAuthor::Webhook(webhook) => webhook.avatar.as_ref().map(|file| file.id.as_str()),
            MessageAuthor::System { avatar, .. } => *avatar,
        }
    }

    pub fn username(&self) -> &str {
        match self {
            MessageAuthor::User(user) => &user.username,
            MessageAuthor::Webhook(webhook) => &webhook.name,
            MessageAuthor::System { username, .. } => username,
        }
    }
}

/// What a bot without the Message Content intent sees of a message: who
/// sent it and where, but no text, embeds, files or components.
impl Message {
    pub fn hide_content(&mut self) {
        if self.content.is_some() {
            self.content = Some(String::new());
        }
        // an AutoMod alert quotes the message that set it off
        if let Some(
            SystemMessage::Text { content } | SystemMessage::AutoModAlert { content, .. },
        ) = &mut self.system
        {
            content.clear();
        }
        self.embeds = None;
        self.attachments = None;
        self.components = None;
        self.poll = None;
        if let Some(SystemMessage::PollEnded { question, winners, .. }) = &mut self.system {
            question.clear();
            winners.clear();
        }
    }
}

